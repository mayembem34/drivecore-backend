        Route::patch('work-orders/{work_order}', [WorkOrderController::class, 'update'])->middleware('can:work_orders.change');
        Route::post('work-orders', [WorkOrderController::class, 'store'])->middleware('can:work_orders.change');
        Route::post('work-orders/{work_order}/{action}', [WorkOrderController::class, 'transition'])->whereIn('action', ['start', 'consume-parts', 'complete', 'cancel'])->middleware('can:work_orders.change');
        Route::get('parts', [InventoryController::class, 'parts'])->middleware('can:parts.view');
        Route::post('parts', [InventoryController::class, 'savePart'])->middleware('can:parts.manage');
        Route::patch('parts/{part}', [InventoryController::class, 'savePart'])->middleware('can:parts.manage');
        Route::post('parts/{part}/adjust', [InventoryController::class, 'adjust'])->middleware('can:parts.manage');
        Route::get('stock-movements', [InventoryController::class, 'movements'])->middleware('can:parts.view');
        Route::get('suppliers', [InventoryController::class, 'suppliers'])->middleware('can:suppliers.view');
        Route::post('suppliers', [InventoryController::class, 'saveSupplier'])->middleware('can:suppliers.manage');
        Route::patch('suppliers/{supplier}', [InventoryController::class, 'saveSupplier'])->middleware('can:suppliers.manage');
        Route::apiResource('purchase-orders', PurchaseOrderController::class)->only(['index', 'show'])->middleware('can:purchase_orders.view');
        Route::apiResource('purchase-orders', PurchaseOrderController::class)->only(['store', 'update'])->middleware('can:purchase_orders.manage');
